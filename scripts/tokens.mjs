// Generates app/tokens.css from brand/colors.json (the app's semantic colour tokens).
// Run: npm run tokens. The site adds no colours of its own.
import { readFileSync, writeFileSync } from 'node:fs';

const colors = JSON.parse(readFileSync(new URL('../brand/colors.json', import.meta.url), 'utf8'));
const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const block = (scheme) =>
  Object.entries(colors[scheme])
    .map(([k, v]) => `  --c-${kebab(k)}: ${v};`)
    .join('\n');

const css = `/* Generated by scripts/tokens.mjs from brand/colors.json. Do not edit by hand. */
:root {
  color-scheme: light dark;
${block('light')}
}

@media (prefers-color-scheme: dark) {
  :root {
${block('dark').replace(/^/gm, '  ')}
  }
}
`;
writeFileSync(new URL('../app/tokens.css', import.meta.url), css);
console.log('app/tokens.css written');
